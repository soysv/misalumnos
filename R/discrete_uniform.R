# ============================================================
# Discrete Uniform Distribution
# 이산 균등분포 U(a, b)
#
# 가능한 값:
# a, a+1, ..., b
# ============================================================


# ------------------------------------------------------------
# 1. PMF
# P(X = k)
# ------------------------------------------------------------

discrete_uniform_pmf <- function(k, a, b) {

  # a와 b가 정수이고 b >= a인지 확인
  if (a %% 1 != 0 || b %% 1 != 0 || b < a) {
    stop("a와 b는 정수이고 b >= a여야 합니다.")
  }

  # k가 a~b 사이의 정수인지 확인
  ok <- (k %% 1 == 0) & (k >= a) & (k <= b)

  # 결과를 0으로 초기화
  result <- numeric(length(k))

  # 가능한 값이면 1 / 가능한 값의 개수
  result[ok] <- 1 / (b - a + 1)

  return(result)
}


# ------------------------------------------------------------
# 2. CDF
# P(X <= q)
# ------------------------------------------------------------

discrete_uniform_cdf <- function(q, a, b) {

  # 결과 저장
  result <- numeric(length(q))

  # q < a이면 확률은 0
  result[q < a] <- 0

  # q >= b이면 확률은 1
  result[q >= b] <- 1

  # a <= q < b인 경우
  inside <- (q >= a) & (q < b)

  result[inside] <-
    (floor(q[inside]) - a + 1) /
    (b - a + 1)

  return(result)
}


# ------------------------------------------------------------
# 3. RNG
# 이산 균등분포에서 랜덤 표본 생성
# ------------------------------------------------------------

discrete_uniform_rnd <- function(n, a, b) {

  # n개의 값을 a~b에서 랜덤하게 추출
  result <- sample(
    a:b,
    size = n,
    replace = TRUE
  )

  return(result)
}


