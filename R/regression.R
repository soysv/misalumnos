# ------------------------------------------------------------
# 1. 단순 선형회귀
# ------------------------------------------------------------

linear_regression <- function(x, y) {

  # y = a + bx 형태의 선형회귀모형
  model <- lm(y ~ x)

  # 회귀 결과 반환
  return(model)
}


