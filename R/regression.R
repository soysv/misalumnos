# ------------------------------------------------------------
# 2. 회귀계수만 확인
# ------------------------------------------------------------

get_regression_coefficients <- function(x, y) {

  model <- lm(y ~ x)

  # 절편(intercept)과 기울기(slope)
  coef(model)
}


# ------------------------------------------------------------
# 3. 회귀선이 있는 산점도
# ------------------------------------------------------------

plot_regression <- function(x, y) {

  # 먼저 산점도
  plot(
    x, y,
    main = "Scatter Plot with Regression Line",
    xlab = "X",
    ylab = "Y"
  )

  # 회귀모형 생성
  model <- lm(y ~ x)

  # 회귀선 추가
  abline(model)

  # 회귀모형 반환
  return(model)
}
