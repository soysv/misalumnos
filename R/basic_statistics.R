# ============================================================
# 기본 통계 함수
# 시험장에서 숫자나 변수 이름만 바꿔서 사용
# ============================================================


# ------------------------------------------------------------
# 1. 평균 (Mean)
# ------------------------------------------------------------

mean_manual <- function(x) {
  # NA(결측값)를 제외하고 평균 계산
  x <- x[!is.na(x)]

  # 평균 = 모든 값의 합 / 데이터 개수
  sum(x) / length(x)
}


