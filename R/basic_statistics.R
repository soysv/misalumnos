# ------------------------------------------------------------
# 2. 분산 (Variance)
# ------------------------------------------------------------

variance_manual <- function(x) {
  # 결측값 제거
  x <- x[!is.na(x)]

  # 평균 계산
  m <- mean(x)

  # 편차 제곱의 합 / (n - 1)
  sum((x - m)^2) / (length(x) - 1)
}


# ------------------------------------------------------------
# 3. 표준편차 (Standard Deviation)
# ------------------------------------------------------------

sd_manual <- function(x) {
  # 분산에 제곱근을 적용
  sqrt(variance_manual(x))
}


# ------------------------------------------------------------
# 4. 공분산 (Covariance)
# ------------------------------------------------------------

covariance_manual <- function(x, y) {
  # x와 y의 길이가 같은지 확인
  if (length(x) != length(y)) {
    stop("x와 y의 길이가 같아야 합니다.")
  }

  # 평균
  x_mean <- mean(x)
  y_mean <- mean(y)

  # 공분산 계산
  sum((x - x_mean) * (y - y_mean)) / (length(x) - 1)
}


# ------------------------------------------------------------
# 5. 상관계수 (Correlation)
# ------------------------------------------------------------

correlation_manual <- function(x, y) {
  # 공분산 / (x의 표준편차 × y의 표준편차)
  covariance_manual(x, y) /
    (sd_manual(x) * sd_manual(y))
}
