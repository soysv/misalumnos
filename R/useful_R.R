# ============================================================
# 시험장에서 자주 사용하는 R 코드
# ============================================================


# ------------------------------------------------------------
# 데이터 생성
# ------------------------------------------------------------

x <- c(1, 2, 3, 4, 5)
y <- c(2, 4, 5, 8, 10)


# ------------------------------------------------------------
# 기본 통계
# ------------------------------------------------------------

mean(x)       # 평균
median(x)     # 중앙값
var(x)        # 분산
sd(x)         # 표준편차


# ------------------------------------------------------------
# 공분산 / 상관계수
# ------------------------------------------------------------

cov(x, y)     # 공분산
cor(x, y)     # 상관계수


# ------------------------------------------------------------
# 선형회귀
# ------------------------------------------------------------

model <- lm(y ~ x)

summary(model)    # 회귀 결과 전체
coef(model)       # 회귀계수
fitted(model)     # 예측값
residuals(model)  # 잔차


# ------------------------------------------------------------
# 산점도
# ------------------------------------------------------------

plot(x, y)


# ------------------------------------------------------------
# 산점도 + 회귀선
# ------------------------------------------------------------

plot(x, y)
abline(lm(y ~ x))


# ------------------------------------------------------------
# 데이터 확인
# ------------------------------------------------------------

head(x)       # 앞부분
length(x)     # 데이터 개수
sum(x)        # 합
min(x)        # 최솟값
max(x)        # 최댓값


# ------------------------------------------------------------
# 조건에 맞는 데이터 선택
# ------------------------------------------------------------

x[x > 3]

x[x >= 2 & x <= 4]


# ------------------------------------------------------------
# 결측값 제거
# ------------------------------------------------------------

x[!is.na(x)]

mean(x, na.rm = TRUE)


# ------------------------------------------------------------
# 난수 생성
# ------------------------------------------------------------

runif(10)          # Uniform 난수
rnorm(10)          # Normal 난수
rpois(10, lambda=3) # Poisson 난수
